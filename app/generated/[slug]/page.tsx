'use client'

import { useState, useEffect } from 'react'
import { useParams } from 'next/navigation'

export default function GeneratedAppPage() {
  const params = useParams()
  const slug = params.slug as string
  const [appData, setAppData] = useState<any>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    fetch(`/api/generated-apps/${slug}`)
      .then(r => { if (!r.ok) throw new Error('App not found'); return r.json() })
      .then(setAppData)
      .catch(e => setError(e.message))
      .finally(() => setLoading(false))
  }, [slug])

  if (loading) return (
    <div className="min-h-screen bg-zinc-950 flex items-center justify-center">
      <div className="text-center">
        <div className="animate-spin w-8 h-8 border-2 border-violet-500 border-t-transparent rounded-full mx-auto mb-4"></div>
        <p className="text-zinc-400">Loading generated app...</p>
      </div>
    </div>
  )

  if (error || !appData) return (
    <div className="min-h-screen bg-zinc-950 flex items-center justify-center">
      <div className="text-center">
        <p className="text-red-400 text-lg mb-2">Failed to load app</p>
        <p className="text-zinc-500 text-sm">{error || 'App not found'}</p>
      </div>
    </div>
  )

  // Parse components and render mock data
  const componentNames = Object.keys(appData.components || {})
  const firstPage = appData.pageSource || ''

  // Extract component info from source
  const componentInfo = componentNames.map((name: string) => {
    const src = appData.components[name]
    const isList = src.includes('.map(item =>')
    const isForm = src.includes('handleSubmit')
    const isDashboard = src.includes('grid-cols')
    
    // Extract interface fields
    const fieldMatch = src.match(/interface \w+ \{([^}]+)\}/)
    const fields: string[] = []
    if (fieldMatch) {
      const lines = fieldMatch[1].split('\n')
      for (const line of lines) {
        const m = line.match(/^\s+(\w+)/)
        if (m && m[1] !== 'id') fields.push(m[1])
      }
    }

    return { name, isList, isForm, isDashboard, fields }
  })

  return (
    <div className="min-h-screen bg-zinc-950 p-6">
      <div className="max-w-6xl mx-auto space-y-8">
        {/* Header */}
        <div className="text-center py-8">
          <div className="inline-flex items-center gap-2 bg-emerald-500/10 border border-emerald-500/20 rounded-full px-4 py-1.5 text-sm text-emerald-400 mb-4">
            🤖 Generated by AI App Generator
          </div>
          <h1 className="text-4xl font-bold mb-2">
            {slug.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')}
          </h1>
          <p className="text-zinc-400">
            Running on AbhiBase • {componentNames.length} components • {Object.keys(appData.apiRoutes || {}).length} API routes
          </p>
        </div>

        {/* Stats */}
        <div className="grid grid-cols-3 gap-4">
          <div className="bg-zinc-900/50 border border-zinc-800 rounded-xl p-4 text-center">
            <div className="text-2xl font-bold text-violet-400">{componentNames.length}</div>
            <div className="text-xs text-zinc-500">Components</div>
          </div>
          <div className="bg-zinc-900/50 border border-zinc-800 rounded-xl p-4 text-center">
            <div className="text-2xl font-bold text-blue-400">{Object.keys(appData.apiRoutes || {}).length}</div>
            <div className="text-xs text-zinc-500">API Routes</div>
          </div>
          <div className="bg-zinc-900/50 border border-zinc-800 rounded-xl p-4 text-center">
            <div className="text-2xl font-bold text-emerald-400">{appData.files?.length || 0}</div>
            <div className="text-xs text-zinc-500">Files</div>
          </div>
        </div>

        {/* Rendered Components */}
        <div className="space-y-6">
          {componentInfo.map((comp: any) => (
            <div key={comp.name} className="bg-zinc-900/50 border border-zinc-800 rounded-2xl overflow-hidden">
              <div className="px-6 py-3 border-b border-zinc-800 flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <span>{comp.isList ? '📋' : comp.isForm ? '📝' : comp.isDashboard ? '📊' : '🧩'}</span>
                  <span className="font-bold text-sm">{comp.name}</span>
                  <span className="text-xs text-zinc-500 bg-zinc-800 px-2 py-0.5 rounded">
                    {comp.isList ? 'list' : comp.isForm ? 'form' : comp.isDashboard ? 'dashboard' : 'component'}
                  </span>
                </div>
                <span className="text-xs text-zinc-600">{comp.fields.length} fields</span>
              </div>
              <div className="p-6">
                {comp.isList && (
                  <div className="space-y-3">
                    {[1, 2, 3].map(i => (
                      <div key={i} className="bg-zinc-800/50 border border-zinc-700 rounded-xl p-4">
                        {comp.fields.slice(0, 3).map((f: string, fi: number) => (
                          <p key={fi} className={`text-sm ${fi === 0 ? 'font-medium text-white' : 'text-zinc-400 mt-1'}`}>
                            {f === 'name' || f === 'title' ? `Sample ${comp.name} ${i}` :
                             f === 'price' || f === 'amount' ? `$${(i * 9.99).toFixed(2)}` :
                             f === 'status' ? ['Active', 'Pending', 'Completed'][i - 1] :
                             f === 'email' ? `user${i}@example.com` :
                             f === 'rating' ? `${(4 + i * 0.2).toFixed(1)} ⭐` :
                             f === 'duration' ? `${i * 15} min` :
                             `Sample ${f} ${i}`}
                          </p>
                        ))}
                      </div>
                    ))}
                  </div>
                )}
                {comp.isForm && (
                  <div className="space-y-4">
                    {comp.fields.map((f: string) => (
                      <div key={f}>
                        <label className="block text-sm text-zinc-400 mb-1">{f}</label>
                        <div className="w-full bg-zinc-800 border border-zinc-700 rounded-lg px-4 py-2 text-zinc-600">
                          {f.includes('email') ? 'user@example.com' :
                           f.includes('price') || f.includes('amount') ? '$0.00' :
                           f.includes('url') ? 'https://' :
                           `Enter ${f}...`}
                        </div>
                      </div>
                    ))}
                    <button className="bg-violet-600 hover:bg-violet-700 px-6 py-2 rounded-lg font-medium text-sm">
                      Save
                    </button>
                  </div>
                )}
                {comp.isDashboard && (
                  <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
                    {comp.fields.slice(0, 4).map((f: string, i: number) => (
                      <div key={f} className="bg-zinc-800 rounded-lg p-4 text-center">
                        <div className="text-2xl font-bold text-violet-400">
                          {f.includes('price') || f.includes('amount') ? `$${((i + 1) * 1250).toLocaleString()}` :
                           f.includes('count') || f.includes('total') ? (i + 1) * 42 :
                           f.includes('progress') ? `${(i + 1) * 20}%` :
                           f.includes('status') ? ['✓', '⏳', '📋', '🔧'][i] :
                           `${(i + 1) * 10}`}
                        </div>
                        <div className="text-xs text-zinc-500 mt-1">{f}</div>
                      </div>
                    ))}
                  </div>
                )}
                {!comp.isList && !comp.isForm && !comp.isDashboard && (
                  <div className="text-zinc-400 text-sm">
                    <p className="mb-2">{comp.name} — {comp.fields.length > 0 ? `Fields: ${comp.fields.join(', ')}` : 'No fields defined'}</p>
                    <p className="text-zinc-600 text-xs">Component source available in the generated files</p>
                  </div>
                )}
              </div>
            </div>
          ))}
        </div>

        {/* Files */}
        {appData.files && appData.files.length > 0 && (
          <div className="bg-zinc-900/50 border border-zinc-800 rounded-2xl p-6">
            <h2 className="text-xl font-bold mb-4">📁 Generated Files</h2>
            <div className="grid md:grid-cols-2 gap-1.5">
              {appData.files.map((f: string) => (
                <div key={f} className="flex items-center gap-2 text-sm bg-zinc-800/50 rounded-lg px-3 py-1.5">
                  <span className={f.endsWith('.sql') ? 'text-amber-400' : f.endsWith('.tsx') ? 'text-blue-400' : f.endsWith('.ts') ? 'text-violet-400' : 'text-zinc-400'}>
                    {f.endsWith('.sql') ? '🗃️' : f.endsWith('.tsx') ? '⚛️' : f.endsWith('.ts') ? '📘' : '📄'}
                  </span>
                  <span className="text-zinc-300">{f}</span>
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  )
}
